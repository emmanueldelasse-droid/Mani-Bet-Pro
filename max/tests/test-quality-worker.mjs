import assert from 'node:assert/strict';
import entry,{refreshPlayerValidation,VALIDATION_KEY} from '../quality-worker.mjs';
const now=new Date('2026-11-03T12:00:00Z');
let checks=0;
const eq=(x,y,m)=>{assert.deepEqual(x,y,m);checks++;};
const state=new Map([['max:health:last',{last_success:now.toISOString()}]]);
let writes=0,listCalls=0;
const kv={async get(key){return state.get(key)??null;},async put(k,v){assert.equal(k,VALIDATION_KEY);state.set(k,JSON.parse(v));writes++;},async list(){listCalls++;return {keys:[],list_complete:true}}};
const first=await refreshPlayerValidation(kv,now);
eq(first.state,'UPDATED','first automatic audit');
eq(first.writes,1,'single write');
eq(state.get(VALIDATION_KEY).paired_predictions,0,'no fake evaluation when empty');
eq(state.get(VALIDATION_KEY).model_mae,null,'no fictitious perfect score');
const second=await refreshPlayerValidation(kv,new Date(now.getTime()+15*60000));
eq(second.state,'CACHED','15min trigger must not repeat audit');
eq(writes,1,'zero redundant writes');
eq(listCalls,1,'zero redundant listings');
const third=await refreshPlayerValidation(kv,new Date(now.getTime()+7*3600000));
eq(third.state,'SOURCE_STALE','stale data must not be treated as fresh');
eq(writes,1,'stale data leaves audit unchanged');
state.set('max:health:last',{last_success:'2026-11-03T19:00:00Z'});
const fourth=await refreshPlayerValidation(kv,new Date('2026-11-03T19:00:00Z'));
eq(fourth.state,'UPDATED','next audit when due and source fresh');
eq(writes,2,'bounded write count');
const r=await entry.fetch(new Request('https://max.example/api/player-validation'),{MAX_STATE:kv});
eq(r.status,200,'audit is read-only accessible');
eq((await r.json()).kind,'RETROSPECTIVE_REPLAY_NOT_PROSPECTIVE','no mislabeling');
const health=await entry.fetch(new Request('https://max.example/api/health'),{MAX_STATE:kv});
eq((await health.json()).points_version,'max-player-points-0.2.0','quality version explicit');
const absent=await entry.fetch(new Request('https://max.example/api/player-validation'),{});
eq(absent.status,503,'storage missing fails closed');
const partial={async get(key){return key==='max:health:last'?{last_success:now.toISOString()}:null},async put(){throw Error('must not write')},async list(){return {keys:[],list_complete:false}}};
eq((await refreshPlayerValidation(partial,now)).state,'SOURCE_LIST_INCOMPLETE','incomplete listing not empty corpus');
console.log(JSON.stringify({status:'PASS',checks,writes,listCalls}));
