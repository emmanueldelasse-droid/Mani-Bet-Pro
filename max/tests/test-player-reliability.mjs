import assert from 'node:assert/strict';
import * as revised from '../points.mjs';
let checks=0;
const ok=(x,msg)=>{assert.ok(x,msg);checks++;};
const eq=(a,b,msg)=>{assert.deepEqual(a,b,msg);checks++;};
const game={id:'401900999',start:'2026-11-04T01:00:00.000Z',status:'STATUS_SCHEDULED',home:{id:'1',name:'Home'},away:{id:'2',name:'Away'}};
const now='2026-11-03T12:00:00.000Z';
function box(i,players=6){
 const start=new Date(Date.parse('2026-10-21T20:00:00Z')+i*86400000).toISOString();
 const team=id=>({totals:{points:114+i%7},players:Array.from({length:players},(_,j)=>({id:id+'-'+j,name:'Player '+id+' '+j,team_id:id,minutes:30+j,points:13+j+i%5}))});
 return {schema_version:'max-box-v1',game_id:String(401800000+i),start,home_id:'1',away_id:'2',teams:{'1':team('1'),'2':team('2')},source_url:'https://example.org/game/'+i,fetched_at:now};
}
const histories=Array.from({length:8},(_,i)=>box(i));
const inj={home:[],away:[]};
const forecast={status:'SIMULATED_UNCALIBRATED',projected_score:{home:117,away:109}};
function predict(xs,gs=game,ns=now){return revised.projectPlayerPoints(gs,xs,inj,[],forecast,ns);}
const full=predict(histories);
eq(full.status,'PLAYER_PROJECTIONS_UNCALIBRATED','both teams have sufficient data');
eq(full.home.players[0].recent_games,8,'count distinct appearances');
eq(full.home.players[0].predicted_points_if_active,19.7,'v0.1 regression fixture unchanged, no untested reweighting');
eq(full.home.players[0].sample_quality,'LOW','eight observations do not imply confidence');
ok(full.home.players.every(p=>p.calibrated===false),'no false calibration');
eq(predict(histories.slice(0,3)).home.players[0].sample_quality,'VERY_LOW','three games explicitly very small sample');
eq(predict(histories.slice(0,2)).home.players[0].predicted_points_if_active,null,'two games do not justify projection');
const baseline=full.home.players.find(p=>p.id==='1-0').baseline_points_last5;
eq(baseline,Math.round(([7,6,5,4,3].map(i=>13+i%5).reduce((a,b)=>a+b,0)/5)*1e4)/1e4,'last5 baseline computed independently');
eq(full.home.players[0].interval_calibration,'NOMINAL_80_NOT_EMPIRICALLY_CALIBRATED','80 percent is not a validated guarantee');
const duplicates=predict([histories[0],histories[0],histories[0]]);
eq(duplicates.home.boxscore_games,1,'duplicate game not counted repeatedly');
eq(duplicates.home.players[0].recent_games,1,'duplicate player appearances cannot inflate sample');
eq(duplicates.home.players[0].predicted_points_if_active,null,'duplicated game cannot unlock predictions');
const duplicatedPlayers=structuredClone(histories.slice(0,3));
for(const b of duplicatedPlayers)b.teams['1'].players.push({...b.teams['1'].players[0]});
eq(predict(duplicatedPlayers).home.players.find(p=>p.id==='1-0').recent_games,3,'duplicate row within game excluded');
const malformed=structuredClone(histories);
for(const b of malformed){b.teams['1'].players[0].points=-1;b.teams['1'].players[1].minutes=0;b.teams['1'].players[2].points='twenty';}
const bad=predict(malformed);
ok(!bad.home.players.some(p=>['1-0','1-1','1-2'].includes(p.id)),'invalid numbers rejected rather than counted as zero');
const future=box(8);future.start='2026-11-03T22:00:00.000Z';
const pastOnly=predict([histories[0],histories[1],future]);
eq(pastOnly.home.players[0].recent_games,2,'results not yet known at snapshot excluded even if before tip');
const oneTeam=Array.from({length:3},(_,i)=>box(i,12));
for(const b of oneTeam)delete b.teams['2'];
const one=predict(oneTeam);
eq(one.home.projectable_players,12,'one covered team remains individually viewable');
eq(one.away.projectable_players,0,'missing opponent remains unknown');
eq(one.status,'INSUFFICIENT','one covered team must not unlock full-match status');
const longMinutes=structuredClone(histories);
for(const b of longMinutes)for(const team of Object.values(b.teams))for(const p of team.players)p.minutes=46;
const capped=predict(longMinutes);
eq(capped.home.players[0].projected_minutes_if_active,42,'displayed minutes match existing scoring cap');
const shifting=structuredClone(histories);
for(let i=0;i<shifting.length;i++)shifting[i].teams['1'].players[0].minutes=i<5?15:32;
ok(predict(shifting).home.players.find(p=>p.id==='1-0').quality_warnings.includes('RECENT_MINUTES_CHANGED'),'role changes flagged without fabricated effect');
eq(predict(histories,{...game,status:'STATUS_FINAL'}).status,'NO_PREMATCH','no retrospective live prediction');
eq(predict(histories,game,'2026-11-05T00:00:00Z').status,'NO_PREMATCH','no prediction after tip');
const resultBox={...box(8),game_id:game.id};
const finalGame={...game,status:'STATUS_FINAL'};
const snap={at:now,game_id:game.id,player_points:full};
const ev=revised.evaluatePlayerPoints(finalGame,resultBox,snap);
eq(ev.matched,12,'twelve actual participants evaluated');
ok(ev.row_predictions.every(r=>Number.isFinite(r.baseline_abs_error)),'same predictions evaluated against independent baseline');
const summary=revised.summarizePlayerPointsEvaluations([ev]);
eq(summary.baseline_comparison.paired_predictions,12,'paired comparison sample exactly matched');
ok(Number.isFinite(summary.baseline_comparison.last5_mean_mae),'baseline accuracy computed');
eq(summary.calibrated,false,'prospective evaluation does not self-certify calibration');
eq(revised.evaluatePlayerPoints(finalGame,resultBox,{...snap,game_id:'OTHER'}),null,'mismatched snapshot ID rejected');
eq(revised.evaluatePlayerPoints(finalGame,resultBox,{...snap,player_points:{...full,match_id:'OTHER'}}),null,'mismatched forecast ID rejected');
eq(revised.evaluatePlayerPoints(finalGame,resultBox,{...snap,at:'2026-11-04T02:00:00Z'}),null,'snapshot after tip rejected');
const absent=structuredClone(full);absent.home.players[0].availability='OFFICIAL_OUT';
const absence=revised.evaluatePlayerPoints(finalGame,resultBox,{...snap,player_points:absent});
eq(absence.availability_error_count,1,'a predicted absence who plays is not silently ignored');
eq(absence.matched,11,'availability mistake separated from conditional scoring sample');
eq(revised.summarizePlayerPointsEvaluations([absence]).availability_error_count,1,'presence error remains in dashboard metrics');
const brokenActual=structuredClone(resultBox);brokenActual.teams['1'].players[0].points=null;
const invalidActual=revised.evaluatePlayerPoints(finalGame,brokenActual,snap);
eq(invalidActual.matched,11,'unknown actual points are not treated as zero');
ok(Number.isFinite(invalidActual.mae),'missing final data cannot poison MAE');
const legacy=structuredClone(ev);for(const row of legacy.row_predictions)delete row.baseline_abs_error;
eq(revised.summarizePlayerPointsEvaluations([legacy]).baseline_comparison.paired_predictions,0,'legacy records do not acquire fabricated baselines');
const audit=revised.auditPlayerHistory(histories,now);
eq(audit.kind,'RETROSPECTIVE_REPLAY_NOT_PROSPECTIVE','historical replay explicit');
eq(audit.status,'INSUFFICIENT_EVIDENCE','short selected history never proves superiority');
eq(audit.input_boxes,8,'audit input counted');
ok(audit.paired_predictions>0,'walk-forward test observations produced');
ok(audit.evaluated_games<8,'first games are training, not mislabeled held-out tests');
ok(Number.isFinite(audit.model_mae)&&Number.isFinite(audit.baseline_last5_mean_mae),'same evaluation subset for model and baseline');
eq(audit.calibrated,false,'replay not calibration claim');
const emptyAudit=revised.auditPlayerHistory(histories.slice(0,3),now);
eq(emptyAudit.paired_predictions,0,'three total games do not yield a holdout after three training games');
eq(emptyAudit.model_mae,null,'lack of evaluations is null, not zero error');
eq(emptyAudit.model_rmse,null,'RMSE cannot be fabricated when empty');
eq(revised.playerAuditInputSignature(histories),revised.playerAuditInputSignature([...histories].reverse()),'audit signature independent of ordering');
const corrected=structuredClone(histories);corrected[0].teams['1'].players[0].points++;
ok(revised.playerAuditInputSignature(corrected)!==revised.playerAuditInputSignature(histories),'score corrections invalidate audit cache');
const audit2=revised.auditPlayerHistory(histories.concat(histories[0]),now);
eq(audit2.paired_predictions,audit.paired_predictions,'duplicate historical match does not inflate accuracy sample');
console.log(JSON.stringify({status:'PASS',checks,audit},null,2));
